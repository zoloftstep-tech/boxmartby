export const LANDING_SLUGS = Object.keys(LANDINGS) as LandingSlug[];

export function getLanding(slug: LandingSlug): LandingPage {
  return LANDINGS[slug];
}

export function getRelatedLandings(slug: LandingSlug): LandingPage[] {
  return LANDING_SLUGS.filter((s) => s !== slug).map((s) => LANDINGS[s]);
}

export function buildLandingJsonLd(page: LandingPage) {
  const url = `${SITE_URL}${page.path}`;
  return [
    {
      "@context": "https://schema.org",
      "@type": "WebPage",
      name: page.h1,
      description: page.description,
      url,
      isPartOf: {
        "@type": "WebSite",
        name: "БОКСМАРТ",
        url: SITE_URL,
      },
      inLanguage: "ru-BY",
    },
    {
      "@context": "https://schema.org",
      "@type": "BreadcrumbList",
      itemListElement: [
        {
          "@type": "ListItem",
          position: 1,
          name: "Главная",
          item: SITE_URL,
        },
        {
          "@type": "ListItem",
          position: 2,
          name: page.title,
          item: url,
        },
      ],
    },
  ];
}
